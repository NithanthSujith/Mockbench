import { createColumnHelper, tableFeatures, useTable } from '@tanstack/react-table'
import type { RequestLogEntry } from '@mockbench/api-contract'
import { ChevronRight } from 'lucide-react'
import { Fragment, useEffect, useMemo, useState } from 'react'
import {
  Button,
  Card,
  EmptyState,
  Input,
  MethodBadge,
  PanelBody,
  PanelHead,
  Select,
  SelectItem,
  Spinner,
  StatusCode,
  Table,
  TBody,
  Td,
  Th,
  THead,
  Tr,
} from '../../../components/ui'
import type { RequestLogFilters } from '../../../lib/query-keys'
import { Editor } from '../../../shell/columns'
import { useProjectForVersions } from '../../versions/queries'
import { useRequests } from '../queries'

const EMPTY_TEXT = 'No requests yet. The log starts filling once this project is deployed.'
const MOCK_ERROR_HINT = 'mocked 404s are your own cases; these were generated by the server'
const RETENTION_NOTE = 'Older entries are pruned automatically.'
const PATH_DEBOUNCE_MS = 250

const features = tableFeatures({})
const helper = createColumnHelper<typeof features, RequestLogEntry>()

function Time({ iso }: { iso: string }) {
  return (
    <time dateTime={iso} title={new Date(iso).toLocaleString()}>
      {new Date(iso).toLocaleTimeString()}
    </time>
  )
}

const columns = helper.columns([
  helper.display({
    id: 'expand',
    header: () => <span className="sr-only">Details</span>,
    cell: () => null,
  }),
  helper.accessor('createdAt', {
    header: 'Time',
    cell: (c) => (
      <span className="mono text-ink-2">
        <Time iso={c.getValue()} />
      </span>
    ),
  }),
  helper.accessor('method', {
    header: 'Method',
    cell: (c) => <MethodBadge method={c.getValue()} />,
  }),
  helper.accessor('path', {
    header: 'Path',
    cell: (c) => <span className="mono">{c.getValue()}</span>,
  }),
  helper.display({
    id: 'case',
    header: 'Case',
    cell: (c) => {
      const row = c.row.original
      return (
        <span className="inline-flex items-center gap-2 text-ink-2">
          {row.caseName ?? '—'}
          {row.mockError ? (
            <span
              data-testid="mock-error-tag"
              title={`${MOCK_ERROR_HINT} (${row.mockError})`}
              className="mono rounded-xs border border-signal-line bg-signal-soft px-1.25 py-px text-micro font-semibold text-signal"
            >
              mock server
            </span>
          ) : null}
        </span>
      )
    },
  }),
  helper.accessor('statusCode', {
    header: 'Status',
    cell: (c) => <StatusCode code={c.getValue()} />,
  }),
  helper.accessor('durationMs', {
    header: 'ms',
    cell: (c) => <span className="mono text-ink-2">{c.getValue()}</span>,
  }),
  helper.accessor('ip', {
    header: 'From',
    cell: (c) => <span className="mono text-ink-2">{c.getValue() ?? '—'}</span>,
  }),
])

function KeyValues({
  title,
  values,
}: {
  title: string
  values: Record<string, string | string[]>
}) {
  const entries = Object.entries(values)
  return (
    <div className="min-w-0">
      <h4 className="eyebrow m-0 mb-1.5">{title}</h4>
      {entries.length === 0 ? (
        <p className="m-0 text-small text-ink-3">None</p>
      ) : (
        <dl className="m-0 grid grid-cols-[max-content_1fr] gap-x-3 gap-y-1">
          {entries.map(([k, v]) => (
            <Fragment key={k}>
              <dt className="mono text-small text-ink-2">{k}</dt>
              <dd className="mono m-0 break-all text-small text-ink">
                {Array.isArray(v) ? v.join(', ') : v}
              </dd>
            </Fragment>
          ))}
        </dl>
      )}
    </div>
  )
}

function LogTable({ data }: { data: RequestLogEntry[] }) {
  const table = useTable({ features, columns, data, getRowId: (row) => row.id })
  const [open, setOpen] = useState<Set<string>>(new Set())
  const toggle = (id: string) =>
    setOpen((prev) => {
      const next = new Set(prev)
      if (!next.delete(id)) next.add(id)
      return next
    })
  return (
    <Table>
      <THead>
        {table.getHeaderGroups().map((group) => (
          <tr key={group.id}>
            {group.headers.map((header) => (
              <Th key={header.id}>
                {header.isPlaceholder ? null : <table.FlexRender header={header} />}
              </Th>
            ))}
          </tr>
        ))}
      </THead>
      <TBody>
        {table.getRowModel().rows.map((row) => {
          const entry = row.original
          const expanded = open.has(entry.id)
          return (
            <Fragment key={row.id}>
              <Tr>
                {row.getAllCells().map((cell) =>
                  cell.column.id === 'expand' ? (
                    <Td key={cell.id} className="w-8 pr-0">
                      <button
                        type="button"
                        aria-expanded={expanded}
                        aria-label={`${expanded ? 'Hide' : 'Show'} details for ${entry.method} ${entry.path}`}
                        onClick={() => toggle(entry.id)}
                        className="grid size-5 place-items-center rounded-xs text-ink-3 hover:text-ink"
                      >
                        <ChevronRight
                          aria-hidden
                          className={`size-3.5 transition-transform ${expanded ? 'rotate-90' : ''}`}
                        />
                      </button>
                    </Td>
                  ) : (
                    <Td key={cell.id}>
                      <table.FlexRender cell={cell} />
                    </Td>
                  ),
                )}
              </Tr>
              {expanded ? (
                <tr data-testid="log-details">
                  <td colSpan={columns.length} className="border-b border-line bg-slab px-3.5 py-3">
                    <div className="grid gap-4 md:grid-cols-2">
                      <KeyValues title="Request headers" values={entry.requestHeaders} />
                      <KeyValues title="Query" values={entry.query} />
                    </div>
                  </td>
                </tr>
              ) : null}
            </Fragment>
          )
        })}
      </TBody>
    </Table>
  )
}

const STATUS_OPTIONS = ['all', '2xx', '4xx', '5xx'] as const
const METHOD_OPTIONS = ['all', 'GET', 'POST', 'PUT', 'PATCH', 'DELETE'] as const

/** Request log: recent requests to the project, filterable and live-refreshing (RUN-08). */
export function LogsScreen() {
  const { projectSlug } = useParams({ strict: false })
  const project = useProjectForVersions(projectSlug).data
  const [status, setStatus] = useState('all')
  const [method, setMethod] = useState('all')
  const [pathText, setPathText] = useState('')
  const [debouncedPath, setDebouncedPath] = useState('')
  const [mockOnly, setMockOnly] = useState(false)
  const [autoRefresh, setAutoRefresh] = useState(true)

  useEffect(() => {
    const id = setTimeout(() => setDebouncedPath(pathText.trim()), PATH_DEBOUNCE_MS)
    return () => clearTimeout(id)
  }, [pathText])

  const filters = useMemo<RequestLogFilters>(() => {
    const f: RequestLogFilters = {}
    if (status !== 'all') f.status = status
    if (method !== 'all') f.method = method
    if (debouncedPath) f.path = debouncedPath
    if (mockOnly) f.mockError = true
    return f
  }, [status, method, debouncedPath, mockOnly])
  const filtered = Object.keys(filters).length > 0

  const query = useRequests(project?.id, filters, autoRefresh)
  const items = useMemo(() => query.data?.pages.flatMap((p) => p.items) ?? [], [query.data])

  if (!project || !projectSlug) return <Editor data-screen="logs/LogsScreen" />

  return (
    <Editor data-screen="logs/LogsScreen">
      <Card>
        <PanelHead>
          <h3 className="m-0">Request log</h3>
          <span className="text-compact text-ink-2">{RETENTION_NOTE}</span>
          <label className="ml-auto flex items-center gap-2 text-compact text-ink-2">
            <input
              type="checkbox"
              checked={autoRefresh}
              onChange={(e) => setAutoRefresh(e.target.checked)}
            />
            Auto-refresh
          </label>
        </PanelHead>
        <PanelBody className="flex flex-wrap items-center gap-2.5">
          <Select
            aria-label="Status"
            mono
            className="w-28"
            value={status}
            onValueChange={setStatus}
          >
            {STATUS_OPTIONS.map((s) => (
              <SelectItem key={s} value={s}>
                {s === 'all' ? 'Any status' : s}
              </SelectItem>
            ))}
          </Select>
          <Select
            aria-label="Method"
            mono
            className="w-32"
            value={method}
            onValueChange={setMethod}
          >
            {METHOD_OPTIONS.map((m) => (
              <SelectItem key={m} value={m}>
                {m === 'all' ? 'Any method' : m}
              </SelectItem>
            ))}
          </Select>
          <Input
            mono
            aria-label="Filter by path"
            placeholder="Filter by path"
            className="w-56"
            value={pathText}
            onChange={(e) => setPathText(e.target.value)}
          />
          <label className="flex items-center gap-2 text-compact text-ink-2">
            <input
              type="checkbox"
              checked={mockOnly}
              onChange={(e) => setMockOnly(e.target.checked)}
            />
            Mock-server errors only
          </label>
        </PanelBody>
        {query.isPending ? (
          <PanelBody>
            <Spinner />
          </PanelBody>
        ) : items.length === 0 ? (
          filtered ? (
            <EmptyState title="No requests match these filters." />
          ) : (
            <EmptyState
              title="No requests yet"
              description={
                project.activeVersion ? (
                  EMPTY_TEXT
                ) : (
                  <>
                    {EMPTY_TEXT}{' '}
                    <Link
                      to="/p/$projectSlug/versions"
                      params={{ projectSlug }}
                      className="text-signal"
                    >
                      Go to Versions
                    </Link>
                  </>
                )
              }
            />
          )
        ) : (
          <>
            <LogTable data={items} />
            {items.some((i) => i.mockError) ? (
              <p className="m-0 px-3.5 pt-3.5 text-small text-ink-3">
                <span className="mono">mock server</span>: {MOCK_ERROR_HINT}.
              </p>
            ) : null}
          </>
        )}
        {query.hasNextPage ? (
          <PanelBody>
            <Button
              variant="ghost"
              disabled={query.isFetchingNextPage}
              onClick={() => void query.fetchNextPage()}
            >
              Load more
            </Button>
          </PanelBody>
        ) : null}
      </Card>
    </Editor>
  )
}
