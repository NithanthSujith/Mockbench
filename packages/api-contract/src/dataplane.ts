// Data-plane constants and schemas (API-CONTRACT section 4): what consumers of /mock/:slug/* see.
// Shared by the Runtime team (server) and the Builder team (curl snippet, Try-it panel).
import { z } from 'zod'
import { Method } from './resources'

/** Header names the mock server reads and writes. */
export const MOCK_HEADERS = {
  version: 'X-Mock-Version',
  route: 'X-Mock-Route',
  case: 'X-Mock-Case',
  error: 'X-Mock-Error',
  status: 'X-Mock-Status',
} as const

/** Query parameter that selects a case by name or id. */
export const MOCK_CASE_QUERY_PARAM = '__case'

/** Case selection, first match wins and there is no fall-through (API-CONTRACT 4.2). */
export const SELECTOR_ORDER = [
  { source: 'header', name: MOCK_HEADERS.case, matches: 'case id or name' },
  { source: 'query', name: MOCK_CASE_QUERY_PARAM, matches: 'case id or name' },
  { source: 'header', name: MOCK_HEADERS.status, matches: 'first case with that status code' },
  { source: 'default', name: null, matches: "the route's default case" },
] as const

/** Response headers every mock response carries. */
export const DIAGNOSTIC_HEADERS = [
  MOCK_HEADERS.version,
  MOCK_HEADERS.route,
  MOCK_HEADERS.case,
] as const

/** Headers added to every data-plane response to keep user-authored content inert (decision D9). */
export const HARDENING_HEADERS = {
  'X-Content-Type-Options': 'nosniff',
  'Content-Security-Policy': 'sandbox',
} as const

export const MOCK_ERROR_CODES = [
  'project_not_found',
  'project_not_published',
  'route_not_found',
  'case_not_found',
  'rate_limited',
  'mock_internal_error',
] as const
export type MockErrorCode = (typeof MOCK_ERROR_CODES)[number]

/** Status for each error the mock server generates itself. */
export const MOCK_ERROR_STATUS: Record<MockErrorCode, number> = {
  project_not_found: 404,
  project_not_published: 503,
  route_not_found: 404,
  case_not_found: 400,
  rate_limited: 429,
  mock_internal_error: 500,
}

const base = { message: z.string(), hint: z.string() }

/** Body of an error generated by the mock server (always sent with `X-Mock-Error: true`). */
export const MockErrorBody = z.discriminatedUnion('error', [
  z.strictObject({ error: z.literal('project_not_found'), ...base, slug: z.string() }),
  z.strictObject({ error: z.literal('project_not_published'), ...base, slug: z.string() }),
  z.strictObject({
    error: z.literal('route_not_found'),
    ...base,
    routes: z.array(z.strictObject({ method: Method, path: z.string() })),
  }),
  z.strictObject({
    error: z.literal('case_not_found'),
    ...base,
    cases: z.array(
      z.strictObject({ name: z.string(), statusCode: z.number().int(), isDefault: z.boolean() }),
    ),
  }),
  z.strictObject({ error: z.literal('rate_limited'), ...base }),
  z.strictObject({ error: z.literal('mock_internal_error'), ...base }),
])
export type MockErrorBody = z.infer<typeof MockErrorBody>
